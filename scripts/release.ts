import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = process.cwd();
const PKG_PATH = resolve(ROOT, "package.json");
const ENV_PATH = resolve(ROOT, "src/config/env.ts");
const CHANGELOG_PATH = resolve(ROOT, "CHANGELOG.md");
const CHANGELOG_RAW_PATH = resolve(ROOT, "src/config/changelog-raw.ts");

const SEMVER_RX = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/;

function readCurrentVersions(): { pkgVersion: string; envVersion: string; changelogVersion: string | null } {
  const pkg = JSON.parse(readFileSync(PKG_PATH, "utf8")) as { version?: string };
  const envSrc = readFileSync(ENV_PATH, "utf8");
  const envMatch = /export const APP_VERSION = "([^"]+)";/.exec(envSrc);
  const changelog = readFileSync(CHANGELOG_PATH, "utf8");
  const clMatch = /^##\s+\[(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\]/m.exec(changelog);

  return {
    pkgVersion: pkg.version ?? "",
    envVersion: envMatch?.[1] ?? "",
    changelogVersion: clMatch?.[1] ?? null,
  };
}

function bumpSemver(current: string, bump: string): string {
  if (SEMVER_RX.test(bump)) return bump;
  const m = SEMVER_RX.exec(current);
  if (!m) throw new Error(`Invalid current version '${current}'`);
  const major = Number(m[1]);
  const minor = Number(m[2]);
  const patch = Number(m[3]);

  if (bump === "major") return `${major + 1}.0.0`;
  if (bump === "minor") return `${major}.${minor + 1}.0`;
  if (bump === "patch") return `${major}.${minor}.${patch + 1}`;
  throw new Error(`Unsupported release target '${bump}'. Use patch | minor | major | X.Y.Z`);
}

function syncRawChangelog(rawMarkdown: string): void {
  const normalized = rawMarkdown.replace(/\r\n/g, "\n");
  const content = [
    "// AUTO-GENERATED FROM /CHANGELOG.md BY scripts/sync-changelog.ts",
    "// Do not edit this file directly. Edit /CHANGELOG.md and run `npm run changelog:sync`.",
    "",
    `export const RAW_CHANGELOG_MD = ${JSON.stringify(normalized)};`,
    "",
  ].join("\n");
  writeFileSync(CHANGELOG_RAW_PATH, content, "utf8");
}

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const dryRun = args.includes("--dry-run");
const targetArg = args.find((a) => !a.startsWith("--"));

const versions = readCurrentVersions();

if (checkOnly || !targetArg) {
  const errors: string[] = [];
  if (!SEMVER_RX.test(versions.pkgVersion)) {
    errors.push(`package.json version '${versions.pkgVersion}' is not valid SemVer 2.0.0`);
  }
  if (versions.pkgVersion !== versions.envVersion) {
    errors.push(`Version drift: package.json (${versions.pkgVersion}) !== src/config/env.ts (${versions.envVersion})`);
  }
  if (versions.changelogVersion !== versions.pkgVersion) {
    errors.push(`Version drift: CHANGELOG.md latest (${versions.changelogVersion ?? "none"}) !== package.json (${versions.pkgVersion})`);
  }

  if (errors.length > 0) {
    console.error("Crease release check failed:");
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }

  console.log(
    `Crease release check passed: v${versions.pkgVersion} is synchronized across package.json, src/config/env.ts, and CHANGELOG.md.`
  );
  if (!checkOnly) {
    console.log("Usage to cut a release: npm run release -- <patch|minor|major|X.Y.Z> [--dry-run]");
  }
  process.exit(0);
}

const nextVersion = bumpSemver(versions.pkgVersion, targetArg);
const today = new Date().toISOString().slice(0, 10);

console.log(`Preparing Crease release: v${versions.pkgVersion} -> v${nextVersion} (${today})${dryRun ? " [DRY RUN]" : ""}`);

if (dryRun) {
  console.log("Would update package.json, src/config/env.ts, CHANGELOG.md, and src/config/changelog-raw.ts.");
  process.exit(0);
}

// 1. Update package.json
const pkgRaw = readFileSync(PKG_PATH, "utf8");
const updatedPkg = pkgRaw.replace(/"version":\s*"[^"]+"/, `"version": "${nextVersion}"`);
writeFileSync(PKG_PATH, updatedPkg, "utf8");

// 2. Update src/config/env.ts
const envRaw = readFileSync(ENV_PATH, "utf8");
const updatedEnv = envRaw.replace(
  /export const APP_VERSION = "[^"]+";/,
  `export const APP_VERSION = "${nextVersion}";`
);
writeFileSync(ENV_PATH, updatedEnv, "utf8");

// 3. Promote [Unreleased] in CHANGELOG.md
const clRaw = readFileSync(CHANGELOG_PATH, "utf8");
const unreleasedMarker = "## [Unreleased]";
const idx = clRaw.indexOf(unreleasedMarker);
if (idx === -1) {
  throw new Error("CHANGELOG.md is missing an '## [Unreleased]' section.");
}

const promotedHeader = [
  "## [Unreleased]",
  "",
  "_No unreleased changes yet. Add new entries under `feat`, `fix`, `security`, `perf`, `refactor`, `test`, `docs`, or `build` before running `npm run release -- <version>`._",
  "",
  "---",
  "",
  `## [${nextVersion}] - ${today}`,
].join("\n");

const updatedCl = clRaw.replace(unreleasedMarker, promotedHeader);
writeFileSync(CHANGELOG_PATH, updatedCl, "utf8");
syncRawChangelog(updatedCl);

console.log(`Release v${nextVersion} prepared cleanly!`);
console.log(`Next steps:`);
console.log(`  1. Review CHANGELOG.md release notes for v${nextVersion}`);
console.log(`  2. Run: npm run lint && npm test && npm run cf:dry-run`);
console.log(`  3. Run: git commit -am "chore(release): v${nextVersion}" && git tag -a v${nextVersion} -m "Release v${nextVersion}"`);
